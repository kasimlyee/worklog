/**
 * Writes an exact type declaration next to every CSS module, so `styles.name` type-checks
 * under `noPropertyAccessFromIndexSignature` and a misspelt class is a compile error.
 *
 *   node scripts/css-module-types.ts          # write *.module.d.css.ts files
 *   node scripts/css-module-types.ts --check  # fail if any is missing or out of date (CI)
 */
import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';

const root = join(import.meta.dirname, '..', 'src');

export function classNames(css: string): readonly string[] {
  const withoutComments = css.replace(/\/\*[\s\S]*?\*\//g, '');
  const names = new Set<string>();
  for (const match of withoutComments.matchAll(/\.(-?[_a-zA-Z][\w-]*)/g)) {
    const name = match[1];
    if (name !== undefined) {
      names.add(name);
    }
  }
  return [...names].sort();
}

export function declaration(names: readonly string[]): string {
  const fields = names.map((name) => `  readonly ${JSON.stringify(name)}: string;`).join('\n');
  return `// Generated by scripts/css-module-types.ts — do not edit.\ndeclare const styles: {\n${fields}\n};\nexport default styles;\n`;
}

function main(): void {
  const check = process.argv.includes('--check');
  const stale: string[] = [];
  const modules = readdirSync(root, { recursive: true, encoding: 'utf8' }).filter((file) => file.endsWith('.module.css'));
  for (const file of modules) {
    const cssPath = join(root, file);
    const typesPath = cssPath.replace(/\.css$/, '.d.css.ts');
    const expected = declaration(classNames(readFileSync(cssPath, 'utf8')));
    const current = existsSync(typesPath) ? readFileSync(typesPath, 'utf8') : null;
    if (current === expected) {
      continue;
    }
    if (check) {
      stale.push(file);
    } else {
      writeFileSync(typesPath, expected);
    }
  }
  if (stale.length > 0) {
    console.error(`CSS module types out of date: ${stale.join(', ')}\nRun: node scripts/css-module-types.ts`);
    process.exitCode = 1;
  }
}

if (import.meta.main) {
  main();
}
